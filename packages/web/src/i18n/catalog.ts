export const catalogs: Readonly<
  Record<Language, Readonly<Record<MessageId, string>>>
> = { en, zh };

export function message(locale: Language, id: MessageId): string {
  return catalogs[locale][id];
}

/**
 * Fills `{name}` placeholders. A placeholder without a value stays visible,
 * so a missing translation is noticed rather than silently erased.
 */
export function formatMessage(
  locale: Language,
  id: MessageId,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return message(locale, id).replace(
    /\{([a-zA-Z][a-zA-Z0-9]*)\}/gu,
    (whole, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : whole,
  );
}
